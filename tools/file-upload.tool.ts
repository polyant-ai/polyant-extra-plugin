import { z } from "zod";
import { PutObjectCommand, S3Client } from "@aws-sdk/client-s3";
import { randomUUID } from "node:crypto";
import { defineTool } from "@polyant-ai/plugin-sdk";
import { errMsg } from "../lib/error.js";
import { extensionFromMime } from "../lib/mime.js";

const MAX_FILE_SIZE = 10 * 1024 * 1024; // 10 MB

/**
 * The agent's bucket, reached ONLY with the static keys the agent holds.
 *
 * The credentials are always passed to the client explicitly, so the AWS SDK
 * never consults its default provider chain: no environment variables, no
 * profile, no ECS task role. An agent's secrets are written by its tenant, and
 * a fallback to the deployment's own identity would let a tenant point that
 * identity at any bucket it can reach. Missing or partial keys are a
 * configuration error, never a reason to look elsewhere.
 */
type S3Resolution =
  | { ok: true; client: S3Client; bucket: string; region: string }
  | { ok: false; error: string };

function resolveS3(secrets: Record<string, string> | undefined): S3Resolution {
  const bucket = secrets?.s3_bucket_name?.trim();
  const region = secrets?.aws_region?.trim();
  const accessKeyId = secrets?.aws_access_key_id?.trim();
  const secretAccessKey = secrets?.aws_secret_access_key?.trim();

  const missing = [
    !bucket && "s3_bucket_name",
    !region && "aws_region",
    !accessKeyId && "aws_access_key_id",
    !secretAccessKey && "aws_secret_access_key",
  ].filter((k): k is string => Boolean(k));
  if (missing.length > 0 || !bucket || !region || !accessKeyId || !secretAccessKey) {
    return { ok: false, error: `S3 not configured for this agent: missing ${missing.join(", ")}.` };
  }

  // There is no configurable endpoint: an agent-supplied one would let whoever
  // writes the agent's secrets send every PUT, with the file in it, to any
  // host. Every call is bounded so a socket that never answers cannot hold the
  // turn; the request bound leaves room for a 10 MB body on a slow link.
  const client = new S3Client({
    region,
    credentials: { accessKeyId, secretAccessKey },
    requestHandler: { connectionTimeout: 5_000, requestTimeout: 60_000, throwOnRequestTimeout: true },
  });
  return { ok: true, client, bucket, region };
}

export default defineTool({
  name: "fileUpload",
  description:
    "Upload a file to S3 and return its key and URL.\n" +
    "Use to persist attachments received from the user or files generated by other tools in the agent's S3 bucket.\n" +
    "Files are stored under `{instanceId}/{conversationId}/{filename}`.\n" +
    "Upload a current message attachment (`attachmentIndex`) or raw base64 data (`base64Data`).\n" +
    "Returns the S3 key and a URL. Limit: 10 MB.",
  category: "storage",
  requiredSecrets: [
    {
      key: "s3_bucket_name",
      type: "text",
      label: "S3 bucket name",
      description: "Bucket the agent's files are uploaded to.",
      sensitive: false,
    },
    {
      key: "aws_region",
      type: "text",
      label: "AWS region",
      description: "Region of the bucket, for example eu-west-1.",
      sensitive: false,
    },
    {
      key: "aws_access_key_id",
      type: "text",
      label: "AWS access key ID",
      description: "Access key of an IAM identity allowed to write to the bucket.",
      sensitive: true,
    },
    {
      key: "aws_secret_access_key",
      type: "text",
      label: "AWS secret access key",
      description: "Secret of the access key above.",
      sensitive: true,
    },
  ],
  inputExamples: [
    {
      label: "Upload first attachment",
      input: { attachmentIndex: 0, base64Data: null, mimeType: null, filename: null },
    },
  ],
  parameters: z.object({
    attachmentIndex: z
      .number()
      .int()
      .min(0)
      .nullable()
      .describe("Index of the attachment to upload (0-based). Use this OR `base64Data`."),
    base64Data: z
      .string()
      .nullable()
      .describe("File data encoded as base64 (alternative to `attachmentIndex`)."),
    mimeType: z
      .string()
      .nullable()
      .describe("MIME type of the file (required when using `base64Data`)."),
    filename: z
      .string()
      .nullable()
      .describe("Custom filename. If omitted, uses the attachment name or generates a UUID."),
  }),
  execute: async (
    {
      attachmentIndex,
      base64Data,
      mimeType,
      filename,
    }: {
      attachmentIndex: number | null;
      base64Data: string | null;
      mimeType: string | null;
      filename: string | null;
    },
    ctx,
  ) => {
    let fileBuffer: Buffer;
    let fileMime: string | undefined = mimeType ?? undefined;
    let fileName: string | undefined = filename ?? undefined;

    if (attachmentIndex != null) {
      const attachment = ctx.attachments?.[attachmentIndex];
      if (!attachment) {
        return { status: "error", error: `No attachment found at index ${attachmentIndex}.` };
      }
      if (!attachment.data) {
        return { status: "error", error: `Attachment at index ${attachmentIndex} has no binary data.` };
      }
      fileBuffer = attachment.data;
      fileMime = fileMime ?? attachment.mimeType;
      fileName = fileName ?? attachment.fileName;
    } else if (base64Data) {
      fileBuffer = Buffer.from(base64Data, "base64");
    } else {
      return { status: "error", error: "No file provided: specify `attachmentIndex` or `base64Data`." };
    }

    if (fileBuffer.length > MAX_FILE_SIZE) {
      return {
        status: "error",
        error: `File too large: ${(fileBuffer.length / (1024 * 1024)).toFixed(1)} MB (max 10 MB).`,
      };
    }

    const s3 = resolveS3(ctx.secrets);
    if (!s3.ok) {
      ctx.audit.log({ action: "storage.fileUpload", success: false, error: s3.error });
      return { status: "not_configured", error: s3.error };
    }
    const { client, bucket, region } = s3;

    // Strip path separators so a filename cannot escape the conversation prefix.
    const rawName = fileName ?? `${randomUUID()}.${extensionFromMime(fileMime)}`;
    const resolvedName = rawName.replace(/[/\\]/g, "_");
    const conversationId = ctx.conversationId ?? "unknown";
    const s3Key = `${ctx.instanceId}/${conversationId}/${resolvedName}`;

    try {
      await client.send(
        new PutObjectCommand({
          Bucket: bucket,
          Key: s3Key,
          Body: fileBuffer,
          ContentType: fileMime ?? "application/octet-stream",
        }),
      );
    } catch (err) {
      const message = errMsg(err);
      console.error(`[fileUpload] upload failed: ${message}`);
      ctx.audit.log({
        action: "storage.fileUpload",
        details: { bucket, key: s3Key },
        success: false,
        error: message,
      });
      return { status: "error", error: message };
    }

    // The raw key went to S3 unchanged (the SDK encodes it for the API); the
    // display URL encodes each segment so a filename with #, ? or a space
    // still gives a link that opens.
    const encodedKey = s3Key.split("/").map(encodeURIComponent).join("/");
    const url = `https://${bucket}.s3.${region}.amazonaws.com/${encodedKey}`;

    ctx.audit.log({
      action: "storage.fileUpload",
      details: { bucket, key: s3Key, sizeBytes: fileBuffer.length, mimeType: fileMime },
      success: true,
    });

    // Keep the latest upload in conversation state so a later turn can reuse
    // its URL: text-only history would drop it.
    ctx.state?.set("lastUploadedFile", {
      key: s3Key,
      url,
      sizeBytes: fileBuffer.length,
      mimeType: fileMime ?? null,
    });

    return { status: "ok", key: s3Key, url, sizeBytes: fileBuffer.length };
  },
});
